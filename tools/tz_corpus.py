#!/usr/bin/env python3
"""Generate the timezone corpus checked by src/compute/test_temporal_zone.zig.

For a set of zones, finds the UTC offset changes of several years through pyarrow (an hourly
grid of local_timestamp), takes instants around each change and runs the zoned temporal
functions on them; local times around each change go through assume_timezone with every
ambiguous / nonexistent choice. One line per case (`E` for an error):

    Z <TAB> zone <TAB> unit <TAB> value <TAB> function[:options] <TAB> result
    A <TAB> zone <TAB> unit <TAB> local value <TAB> ambiguous:nonexistent <TAB> result

Results: an integer (stored value), `T` / `F` (bool), or hex text (strftime, cast to string).

pyarrow lives in the user site, so run it with `python -P` (isolated mode hides it):
    python -P tools/tz_corpus.py src/compute/testdata/tz_corpus.tsv
"""
from __future__ import annotations

import sys

import pyarrow as pa
import pyarrow.compute as pc

EXPECTED_PYARROW = "26."
ZONES = ["America/New_York", "Europe/London", "Europe/Dublin", "Europe/Moscow", "Australia/Sydney",
         "Australia/Lord_Howe", "Pacific/Chatham", "Asia/Tehran", "America/Sao_Paulo", "America/Santiago",
         "America/St_Johns", "Africa/Casablanca", "Pacific/Apia", "Antarctica/Troll"]
YEARS = [1995, 2011, 2021, 2037, 2045]
# Milliseconds only for a few zones (the unit changes the arithmetic, not the zone logic).
MS_ZONES = {"America/New_York", "Australia/Lord_Howe", "Pacific/Chatham"}
PER = {"s": 1, "ms": 1000}
EXTRACT = ["year", "month", "day", "hour", "minute", "day_of_week", "iso_week", "is_dst"]
ROUNDS = [("floor_temporal", "minute", 15), ("ceil_temporal", "hour", 1), ("round_temporal", "hour", 1),
          ("floor_temporal", "day", 1), ("round_temporal", "month", 1), ("floor_temporal", "hour", 2)]


def hx(s: str) -> str:
    return s.encode("utf-8").hex()


def changes(zone: str, year: int) -> list[int]:
    """UTC seconds of the offset changes of `year` (hour grid: the first hour of a new offset)."""
    start = int(pa.scalar(f"{year}-01-01T00:00:00Z").cast(pa.timestamp("s", "UTC")).value)
    grid = list(range(start, start + 366 * 86400, 900))
    local = pc.local_timestamp(pa.array(grid, pa.timestamp("s", zone))).cast(pa.int64()).to_pylist()
    out = []
    for i in range(1, len(grid)):
        if local[i] - grid[i] != local[i - 1] - grid[i - 1]:
            out.append(grid[i])
    return out


def one(fn, arr):
    try:
        r = fn(arr)
        return r
    except Exception:  # noqa: BLE001 - every pyarrow error is an expected E
        return None


def fmt(v) -> str:
    if v is None:
        return "E"
    if isinstance(v, bool):
        return "T" if v else "F"
    if isinstance(v, str):
        return hx(v)
    return str(v)


def main() -> None:
    if not pa.__version__.startswith(EXPECTED_PYARROW):
        sys.exit(f"pyarrow {pa.__version__}: expected {EXPECTED_PYARROW}x")
    out = [f"# Generated by tools/tz_corpus.py with pyarrow {pa.__version__}; do not edit."]
    for zone in ZONES:
        instants: set[int] = set()
        for year in YEARS:
            for t in changes(zone, year):
                # The grid finds the first quarter hour of the new offset: look back to the
                # exact second (transitions fall on whole minutes).
                lo = t - 900
                local = pc.local_timestamp(pa.array(list(range(lo, t + 1, 60)), pa.timestamp("s", zone))).cast(pa.int64()).to_pylist()
                exact = t
                for k, l in enumerate(local):
                    if l - (lo + 60 * k) == local[-1] - t:
                        exact = lo + 60 * k
                        break
                for d in (-3601, -1, 0, 1, 1799, 3599):
                    instants.add(exact + d)
        instants_sorted = sorted(instants)
        for unit, per in PER.items():
            if unit == "ms" and zone not in MS_ZONES:
                continue
            ty = pa.timestamp(unit, zone)
            for v in instants_sorted:
                x = v * per + (per // 3 if per > 1 else 0)
                a = pa.array([x], ty)
                cases = [("local_timestamp", lambda a: pc.local_timestamp(a).cast(pa.int64())),
                         ("strftime", lambda a: pc.strftime(a, format="%Y-%m-%dT%H:%M:%S%z")),
                         ("strftime_Z", lambda a: pc.strftime(a, format="%Z")),
                         ("cast_string", lambda a: a.cast(pa.string())),
                         ("cast_date32", lambda a: a.cast(pa.date32()).cast(pa.int32())),
                         ("cast_time64", lambda a: a.cast(pa.time64("us")).cast(pa.int64())),
                         ("days_between", lambda a: pc.days_between(a, pa.array([x + 90000 * per], ty))),
                         ("hours_between", lambda a: pc.hours_between(a, pa.array([x + 90000 * per], ty)))]
                cases += [(f, (lambda f: lambda a: getattr(pc, f)(a))(f)) for f in EXTRACT]
                cases += [(f"{f}:{u}:{m}", (lambda f, u, m: lambda a: getattr(pc, f)(a, multiple=m, unit=u).cast(pa.int64()))(f, u, m))
                          for f, u, m in ROUNDS]
                for name, fn in cases:
                    r = one(fn, a)
                    out.append(f"Z\t{zone}\t{unit}\t{x}\t{name}\t{fmt(None if r is None else r.to_pylist()[0])}")
            # assume_timezone on the local times around each change.
            locals_ = set()
            for v in instants_sorted:
                l = pc.local_timestamp(pa.array([v], pa.timestamp("s", zone))).cast(pa.int64()).to_pylist()[0]
                for d in (0, 1800):
                    locals_.add((l + d) * per)
            for l in sorted(locals_):
                for amb in ("raise", "earliest", "latest"):
                    for non in ("raise", "earliest", "latest"):
                        try:
                            r = pc.assume_timezone(pa.array([l], pa.timestamp(unit)), timezone=zone, ambiguous=amb, nonexistent=non)
                            res = str(r.cast(pa.int64()).to_pylist()[0])
                        except Exception:  # noqa: BLE001
                            res = "E"
                        out.append(f"A\t{zone}\t{unit}\t{l}\t{amb}:{non}\t{res}")
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(len(out) - 1, "cases")


if __name__ == "__main__":
    main()
