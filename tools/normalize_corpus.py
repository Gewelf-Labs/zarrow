#!/usr/bin/env python3
"""Generate the utf8_normalize corpus checked by src/compute/test_string_normalize.zig.

Every code point (surrogates excluded) is normalized to NFC, NFD, NFKC and NFKD by Python's
`unicodedata` (which must be Unicode 17.0.0, the version of zarrow's tables) and by pyarrow 26
(utf8proc); the script fails unless both agree. Per form and per block of 4096 code points it
writes an FNV-1a 64 hash of the results (each result's UTF-8 bytes then 0xFF):

    H <TAB> form <TAB> block <TAB> hash (16 hex digits)

and seeded random sequences (starters, combining marks of several classes, Hangul jamo and
syllables, compatibility characters), with both pyarrow's and unicodedata's results:

    S <TAB> input-hex <TAB> nfc-hex <TAB> nfd-hex <TAB> nfkc-hex <TAB> nfkd-hex

pyarrow lives in the user site, so run it with `python -P` (isolated mode hides it):
    python -P tools/normalize_corpus.py src/compute/testdata/normalize_corpus.tsv
"""
from __future__ import annotations

import random
import sys
import unicodedata

import pyarrow as pa
import pyarrow.compute as pc

FORMS = ["NFC", "NFD", "NFKC", "NFKD"]
POOL = ("a e o u A E O s S k K n N y Y Å Å ẛ é ö İ ı Ω Ω "
        "̀ ́ ̂ ̃ ̈ ̣ ̧ ̨ ̛ ͅ ֑ ְ ٓ "
        "ٔ ٕ ़ া ে ା େ ா ெ ೂ ೆ ാ െ "
        "් ා ෙ ཱ ི ྀ ီ ဥ ᬵ ᬅ ゙ ゚ か "
        "ハ ᄀ ᄒ ᅡ ᅵ ᆨ ᇂ 가 힣 각 ᄃ ᅪ "
        "ﬁ ﷺ ① ½ ẞ Ǆ Ⅳ ㌀ Ａ     ̈́ ཱི "
        "\U0001d15e \U0001d165 \U0001d16d \U000110ab \U000110ba \U0001133e \U00011347 \U000114b9 "
        "\U000115af \U00011935 \U0001611e \U00016d63 \U0001e5ee \U0001e5ef \U00016ff0 \U000105c9 "
        "\U00011383 \U000113c2 \U000113b8 \U000113c9 \U0001e130 \U0002f800 क़ ⫝̸ ̀").split(" ")


def fnv(data: bytes, h: int) -> int:
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main() -> None:
    if unicodedata.unidata_version != "17.0.0":
        sys.exit(f"unicodedata is Unicode {unicodedata.unidata_version}: expected 17.0.0")
    if not pa.__version__.startswith("26."):
        sys.exit(f"pyarrow {pa.__version__}: expected 26.x")
    out = [f"# Generated by tools/normalize_corpus.py with pyarrow {pa.__version__} and Python unicodedata "
           f"{unicodedata.unidata_version}; do not edit."]
    cps = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]
    strs = [chr(c) for c in cps]
    for form in FORMS:
        arrow = pc.utf8_normalize(pa.array(strs), form).to_pylist()
        hashes: dict[int, int] = {}
        for cp, s, a in zip(cps, strs, arrow):
            want = unicodedata.normalize(form, s)
            if want != a:
                sys.exit(f"pyarrow and unicodedata disagree on {form} of U+{cp:04X}")
            b = cp >> 12
            hashes[b] = fnv(want.encode("utf-8") + b"\xff", hashes.get(b, 0xCBF29CE484222325))
        for b in sorted(hashes):
            out.append(f"H\t{form}\t{b}\t{hashes[b]:016x}")
    rng = random.Random(20)
    seqs = []
    for _ in range(4000):
        seqs.append("".join(rng.choice(POOL) for _ in range(rng.randint(1, 8))))
    arrow = {f: pc.utf8_normalize(pa.array(seqs), f).to_pylist() for f in FORMS}
    for i, s in enumerate(seqs):
        row = [s.encode("utf-8").hex()]
        for f in FORMS:
            want = unicodedata.normalize(f, s)
            if want != arrow[f][i]:
                sys.exit(f"pyarrow and unicodedata disagree on {f} of {s!r}")
            row.append(want.encode("utf-8").hex())
        out.append("S\t" + "\t".join(row))
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
