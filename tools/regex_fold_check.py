#!/usr/bin/env python3
"""Write RE2's case folding orbits (as pyarrow 26 matches `(?i)`) to src/regex/testdata.

Candidates are the code points of the simple case mapping tables in
src/compute/unicode_tables.zig (Unicode 17.0.0) plus every code point Python's unicodedata
maps or folds. For each candidate c, pyarrow's match_substring_regex with `(?i)^\\x{c}$` over
all candidates gives c's orbit. Orbits of two or more code points are written one per line
(hex, space-separated); src/regex/test_regex.zig checks `parse.foldKey` against them.

pyarrow lives in the user site, so run it with `python -P`:
    python -P tools/regex_fold_check.py src/regex/testdata/fold_orbits.txt
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pyarrow as pa
import pyarrow.compute as pc


def table_code_points(path: Path) -> set[int]:
    cps = set()
    pat = re.compile(r"\.first = 0x([0-9A-F]+), \.last = 0x([0-9A-F]+), \.stride2 = (\d), \.delta = (-?\d+)")
    for m in pat.finditer(path.read_text(encoding="utf-8")):
        first, last, stride2, delta = int(m[1], 16), int(m[2], 16), int(m[3]), int(m[4])
        for c in range(first, last + 1, 2 if stride2 else 1):
            cps.add(c)
            cps.add(c + delta)
    return cps


def main() -> None:
    assert pa.__version__.startswith("26."), pa.__version__
    root = Path(__file__).resolve().parent.parent
    cands = table_code_points(root / "src/compute/unicode_tables.zig")
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        ch = chr(c)
        if ch.lower() != ch or ch.upper() != ch or ch.casefold() != ch:
            cands.add(c)
    cands = sorted(c for c in cands if not 0xD800 <= c <= 0xDFFF)
    arr = pa.array([chr(c) for c in cands])
    orbits = set()
    for c in cands:
        hits = pc.match_substring_regex(arr, "(?i)^\\x{%x}$" % c).to_pylist()
        orbit = tuple(cands[i] for i, h in enumerate(hits) if h)
        assert c in orbit
        if len(orbit) > 1:
            orbits.add(orbit)
    lines = [" ".join("%x" % c for c in o) for o in sorted(orbits)]
    Path(sys.argv[1]).write_text(
        "# RE2 (?i) orbits from pyarrow %s; generated by tools/regex_fold_check.py.\n" % pa.__version__
        + "\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(len(cands), "candidates,", len(orbits), "orbits")


if __name__ == "__main__":
    main()
